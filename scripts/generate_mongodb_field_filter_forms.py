#!/usr/bin/env python3
"""Generate the six entity tools and beacon2_cnv from the 2.2.4 mapping table.

Their MongoDB forms must present exactly the fields 2.2.4 offered, so they are
generated from beacon2_import/data/search_options_2x.tsv -- the same table that
drives the coverage test and the README's migration tables -- with 2.2.4's own labels
and help text. Edit the table or this script, never the generated XML.

    python3 scripts/generate_mongodb_field_filter_forms.py
"""

from __future__ import annotations

import csv
import json
import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HERE = ROOT / "tools" / "beacon2-import"
TABLE = ROOT / "beacon2_import" / "data" / "search_options_2x.tsv"
#: The 2.2.4 forms' own labels and help text, extracted from its tool XML.
LABELS = Path(__file__).resolve().parent / "mongodb_field_filter_labels.json"

ENTITIES = {
    # 2.2.4 subcommand: (singular entity, tool title, description, sample record id, column)
    "biosamples": ("biosample", "Biosamples", "retrieve biosamples, and optionally their variants",
                   "cellzbs-kftvksg5", "biosample_id"),
    "individuals": ("individual", "Individuals", "retrieve individuals",
                    "cellzind-b13A4316", "individual_id"),
    "analyses": ("analysis", "Analyses", "retrieve analyses", "cellzcs-kftwtzhm", "analysis_id"),
    "runs": ("run", "Runs", "retrieve sequencing runs", "cellzrun-0001", "run_id"),
    "cohorts": ("cohort", "Cohorts", "retrieve cohorts", "cellz", "cohort_id"),
    "datasets": ("dataset", "Datasets", "retrieve datasets", "cellz", "dataset_id"),
}

HEADER = """<tool id="beacon2_{tool}" name="Beacon2 {title}" version="@TOOL_VERSION@+galaxy@VERSION_SUFFIX@" profile="@PROFILE@">
    <!-- GENERATED by generate_mongodb_field_filter_forms.py from search_options_2x.tsv. Do not edit by hand. -->
    <description>{description} from federated beacons or a self-hosted database</description>
    <macros>
        <import>macros.xml</import>
    </macros>
    <expand macro="creators"/>
    <expand macro="xrefs"/>
    <expand macro="requirements"/>
"""

MONGO_HEAD = """    beacon2-query {sub}
        --transport mongodb
        --db-host '$connection.db_host'
        --db-port $connection.db_port
        --database '$connection.database'
        --collection '$connection.collection'
        --credentials-file '$credentials'"""

API_PAGINATION = """        --granularity '$connection.granularity'
        --limit $connection.pagination.limit
        --skip $connection.pagination.skip
        #if str($connection.pagination.sample)
            --sample $connection.pagination.sample
        #end if"""

HELP_TRANSPORTS = """**Two ways to narrow a query, one per connection**

On the *Beacon v2 API* the tool takes **filters**: ontology terms such as
``NCIT:C3058``, which each beacon maps onto its own records. The API has no way
to match a field's value directly.

On a *self-hosted MongoDB* the tool takes **fields**: the same named fields the
2.2.x tools offered, each matched exactly against a document path shown in its
help. A raw collection has no mapping from ontology terms to fields, so filters
are not offered there."""


def rows(subcommand: str) -> list[dict[str, str]]:
    lines = [l for l in TABLE.read_text().splitlines() if l and not l.startswith("#")]
    return [r for r in csv.DictReader(lines, delimiter="\t") if r["subcommand"] == subcommand]


def field_params(subcommand: str, labels: dict, skip: tuple[str, ...] = ()) -> str:
    out = []
    old = labels.get(subcommand, {})
    for row in rows(subcommand):
        if row["dest"] in skip:
            continue
        label = old.get(row["long"], {}).get("label") or row["label"].upper()
        help_text = old.get(row["long"], {}).get("help") or ""
        if row["kind"] == "field":
            help_text = (help_text + " " if help_text else "") + f"Matched exactly against {row['target']}."
        if row["note"]:
            help_text += f" Note: {row['note']}."
        kind = 'type="integer"' if row["type"] == "int" else 'type="text"'
        out.append(f'            <param name="{row["dest"]}" {kind} value="" optional="true" '
                   f'label="{escape(label)}" help="{escape(help_text.strip())}"/>')
    return "\n".join(out)


def field_args(subcommand: str, skip: tuple[str, ...] = ()) -> str:
    out = []
    for row in rows(subcommand):
        if row["dest"] in skip:
            continue
        ref = f"$connection.mongo_fields.{row['dest']}"
        if row["kind"] == "field":
            arg = f"--field '{row['target']}={ref}'"
        else:
            arg = f"{row['target']} '{ref}'"
        out.append(f"        #if str({ref})\n            {arg}\n        #end if")
    return "\n".join(out)


def entity_tool(subcommand: str, labels: dict) -> str:
    singular, title, description, record_id, column = ENTITIES[subcommand]
    nested_input = nested_arg = ""
    if singular == "biosample":
        nested_input = """
                        <param name="nested" type="select" label="Also retrieve"
                               help="Fetched in one request by the beacon, not assembled here from separate queries.">
                            <option value="none" selected="true">Nothing: the biosample record only</option>
                            <option value="genomicVariant">All variants observed in this biosample</option>
                            <option value="analysis">All analyses of this biosample</option>
                        </param>
                        <param name="variant_classes" type="select" multiple="true" optional="true"
                               label="Variant classes (only used when retrieving variants)">
                            <option value="CNV">Copy number variants</option>
                            <option value="SMALL_VARIANT">SNV / small indel</option>
                            <option value="SV">Structural variants</option>
                        </param>"""
        nested_arg = """
            #if str($connection.lookup.nested) != "none"
                --nested-entity '$connection.lookup.nested'
                #if str($connection.lookup.nested) == "genomicVariant" and str($connection.lookup.variant_classes) != "None"
                    --variant-classes '${str($connection.lookup.variant_classes)}'
                #end if
            #end if"""
    return HEADER.format(tool=subcommand, title=title, description=description) + f"""    <command detect_errors="exit_code"><![CDATA[
#if str($connection.transport) == "api"
    #set $filters = $connection.filters
    beacon2-query entity --entity {singular}
        @PROVIDER_ARGS@
{API_PAGINATION}
        #if str($connection.lookup.mode) == "by_id"
            --entity-id '$connection.lookup.entity_id'{nested_arg}
        #end if
        @FILTER_ARGS@
        @OUTPUT_ARGS@
#else
{MONGO_HEAD.format(sub=f"entity --entity {singular}")}
{field_args(subcommand)}
        @OUTPUT_ARGS@
#end if
    ]]></command>
    <expand macro="credentials_configfile"/>
    <inputs>
        <conditional name="connection">
            <param name="transport" type="select" label="Beacon connection">
                <option value="api" selected="true">Beacon v2 API</option>
                <option value="mongodb">Direct MongoDB (self-hosted)</option>
            </param>
            <when value="api">
                <expand macro="beacon_providers"/>
                <conditional name="lookup">
                    <param name="mode" type="select" label="What to retrieve">
                        <option value="query" selected="true">{title} matching filters</option>
                        <option value="by_id">One {singular} by identifier</option>
                    </param>
                    <when value="query"/>
                    <when value="by_id">
                        <param name="entity_id" type="text" value="" optional="false" label="Identifier"
                               help="As used by that beacon. Identifiers are local to each beacon."/>{nested_input}
                    </when>
                </conditional>
                <expand macro="beacon_granularity"/>
                <expand macro="beacon_filters"/>
                <expand macro="beacon_pagination"/>
            </when>
            <when value="mongodb">
                <expand macro="mongo_connection"/>
                <section name="mongo_fields" title="Fields to match (each one exact; all must match)" expanded="true">
{field_params(subcommand, labels)}
                </section>
            </when>
        </conditional>
    </inputs>
    <expand macro="beacon_outputs"/>
    <tests>
        <test expect_num_outputs="2">
            <conditional name="connection">
                <param name="transport" value="api"/>
                <param name="providers" value="org.cancercelllines"/>
            </conditional>
            <output name="results">
                <assert_contents>
                    <has_text text="{column}"/>
                    <has_text text="{record_id}"/>
                </assert_contents>
            </output>
            <output name="outcomes">
                <assert_contents>
                    <has_text text="org.cancercelllines"/>
                    <has_text text="ok"/>
                    <has_n_lines n="2"/>
                </assert_contents>
            </output>
        </test>
    </tests>
    <help><![CDATA[
**What it does**

@HELP_READS@

Retrieves {singular} records from the beacons you select, or from a self-hosted
Beacon MongoDB database.

{HELP_TRANSPORTS}

@HELP_OUTPUTS@
    ]]></help>
    <expand macro="citations"/>
</tool>
"""


def cnv_tool(labels: dict) -> str:
    positional = ("chromosome", "start", "end", "variantType")
    old = labels.get("cnv", {})

    def old_label(flag, fallback):
        return escape(old.get(flag, {}).get("label") or fallback)

    return HEADER.format(tool="cnv", title="CNV",
                         description="find copy number variants") + f"""    <command detect_errors="exit_code"><![CDATA[
#if str($connection.transport) == "api"
    #set $filters = $connection.filters
    beacon2-query cnv
        @PROVIDER_ARGS@
        --reference-name '$connection.reference_name'
        --assembly '$connection.assembly'
        --start $connection.start
        --end $connection.end
{API_PAGINATION}
        #if str($connection.cnv_terms.variant_type.mode) == "efo"
            --class-term 'CNV=$connection.cnv_terms.variant_type.term'
            --expand-hierarchy '$connection.cnv_terms.variant_type.expand_hierarchy'
        #elif str($connection.cnv_terms.variant_type.mode) != "none"
            --class-term 'CNV=$connection.cnv_terms.variant_type.term'
        #end if
        @FILTER_ARGS@
        @OUTPUT_ARGS@
#else
{MONGO_HEAD.format(sub="cnv")}
        --stored-coordinates
        #if str($connection.chromosome)
            --reference-name '$connection.chromosome'
        #end if
        #if str($connection.start)
            --start $connection.start
        #end if
        #if str($connection.end)
            --end $connection.end
        #end if
        #if str($connection.variantType)
            --variant-type '$connection.variantType'
        #end if
{field_args("cnv", skip=positional)}
        @OUTPUT_ARGS@
#end if
    ]]></command>
    <expand macro="credentials_configfile"/>
    <inputs>
        <conditional name="connection">
            <param name="transport" type="select" label="Beacon connection">
                <option value="api" selected="true">Beacon v2 API</option>
                <option value="mongodb">Direct MongoDB (self-hosted)</option>
            </param>
            <when value="api">
                <expand macro="beacon_providers"/>
                <param name="reference_name" type="text" value="" optional="false" label="Chromosome"
                       help="17, chr17 or NC_000017.11 are all accepted."/>
                <param name="assembly" type="select" label="Genome assembly">
                    <option value="GRCh38" selected="true">GRCh38 (hg38)</option>
                    <option value="GRCh37">GRCh37 (hg19)</option>
                </param>
                <param name="start" type="integer" value="" min="1" label="Start position" help="1-based."/>
                <param name="end" type="integer" value="" min="1" label="End position" help="1-based, inclusive."/>
                <expand macro="beacon_cnv_terms"/>
                <expand macro="beacon_granularity"/>
                <expand macro="beacon_filters"/>
                <expand macro="beacon_pagination"/>
            </when>
            <when value="mongodb">
                <expand macro="mongo_connection"/>
                <param name="chromosome" type="text" value="" optional="true" label="{old_label('--chromosome', 'CHROMOSOME')}"
                       help="Chromosome number, without chr."/>
                <param name="start" type="integer" value="" optional="true" label="{old_label('--start', 'START')}"
                       help="As stored in the database, exactly as the 2.2.x tool took it. A CNV must start at or after this."/>
                <param name="end" type="integer" value="" optional="true" label="{old_label('--end', 'END')}"
                       help="As stored in the database. A CNV must end at or before this."/>
                <param name="variantType" type="text" value="" optional="true" label="{old_label('--variantType', 'VARIANT TYPE')}"
                       help="E.g. DEL or DUP."/>
                <section name="mongo_fields" title="Further fields (each one exact; all must match)" expanded="true">
{field_params("cnv", labels, skip=positional)}
                </section>
            </when>
        </conditional>
    </inputs>
    <expand macro="beacon_outputs"/>
    <tests>
        <test expect_num_outputs="2">
            <conditional name="connection">
                <param name="transport" value="api"/>
                <param name="providers" value="org.cancercelllines"/>
                <param name="reference_name" value="3"/>
                <param name="start" value="195728638"/>
                <param name="end" value="198169247"/>
            </conditional>
            <output name="results">
                <assert_contents>
                    <has_text text="CNV"/>
                    <has_text text="EFO:0030070"/>
                </assert_contents>
            </output>
            <output name="outcomes">
                <assert_contents>
                    <has_text text="org.cancercelllines"/>
                    <has_text text="ok"/>
                </assert_contents>
            </output>
        </test>
    </tests>
    <help><![CDATA[
**What it does**

@HELP_READS@

Finds copy number variants on the beacons you select, or in a self-hosted
Beacon MongoDB database. It carries every field the 2.2.x CNV tool offered.

**The two connections match positions differently**

On a *self-hosted MongoDB*, start and end are taken exactly as stored, and a CNV
matches if it lies **within** them: it starts at or after the start and ends at
or before the end. That is the 2.2.x behaviour, unchanged, so existing analyses,
including the GTN CNV tutorial, give the same results.

On the *Beacon v2 API*, positions are 1-based and the query is a Beacon range
query, which matches any CNV that **overlaps** the region at all. The same
window can therefore return more on the API than from MongoDB.

{HELP_TRANSPORTS}

@HELP_CNV_TERMS@

@HELP_OUTPUTS@
    ]]></help>
    <expand macro="citations"/>
</tool>
"""


def main() -> None:
    labels = json.loads(LABELS.read_text())
    for subcommand in ENTITIES:
        (HERE / f"beacon2_{subcommand}.xml").write_text(entity_tool(subcommand, labels))
    (HERE / "beacon2_cnv.xml").write_text(cnv_tool(labels))
    print("generated:", [f"beacon2_{s}.xml" for s in ENTITIES] + ["beacon2_cnv.xml"])


if __name__ == "__main__":
    main()
